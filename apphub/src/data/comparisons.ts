/**
 * نموذج بيانات المقارنات + محتوى المقارنات نفسه
 * أي مقارنة جديدة = عنصر جديد في المصفوفة بس، والصفحة بتتولد أوتوماتيك.
 */

export interface ComparisonAppRef {
  /** نفس slug بتاع صفحة التطبيق في /apps/[slug] */
  appSlug: string;
  /** الاسم المعروض بالعربي */
  name: string;
  /** إيموجي أو مسار لوجو */
  icon: string;
  /** تقييم التطبيق المعروض في الدليل */
  rating: number;
}

export interface CriterionRow {
  label: string;
  /** قيمة كل تطبيق بالترتيب نفسه بتاع apps[] */
  values: string[];
  /** رقم التطبيق الفائز في الصف ده (اختياري — بيتحدد بالهايلايت) */
  winner?: number;
}

export interface PricingPlan {
  appIndex: number;
  name: string;
  /** السعر نص جاهز للعرض، مثال: "١٠٠ ج.م / شهريًا" */
  price: string;
  note?: string;
}

export interface CountryPricing {
  country: string;
  plans: PricingPlan[];
  /** تنويه أسفل الجدول، مثال: الأسعار لا تشمل الضريبة */
  footnote?: string;
}

export interface ComparisonFAQ {
  q: string;
  a: string;
}

export interface Comparison {
  /** مقطع الرابط: netflix-vs-shahid — إنجليزي lowercase، متكررش مرتين */
  slug: string;
  category: string;
  apps: ComparisonAppRef[];

  /** SEO */
  metaTitle: string;
  metaDescription: string;
  /** العنوان الرئيسي الظاهر fو الصفحة */
  h1: string;
  intro: string;

  /** الخلاصة السريعة */
  verdict: string;
  /** "الأفضل لو..." لكل موقف */
  bestFor: { appIndex: number; label: string }[];

  criteria: CriterionRow[];
  pros: string[][];
  cons: string[][];
  pricing: CountryPricing[];
  faq: ComparisonFAQ[];
  /** slugs مقارنات ذات صلة — بتظهر أسفل الصفحة (روابط داخلية) */
  related: string[];

  /** ISO date — بيطلع في الصفحة وفي schema وlastmod */
  updatedAt: string;
}

